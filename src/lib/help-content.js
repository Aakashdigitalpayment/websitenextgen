const norm = v => String(v || '').toLowerCase().normalize('NFC').replace(/\s+/g, ' ').trim();

/** Articles matching every word of `q` (title, summary, steps, tips, keywords in both languages). */
function search(list, q) {
  const words = norm(q).split(' ').filter(Boolean).slice(0, 8);
  if (!words.length) return list;
  return list.filter(a => { const t = norm(a.text); return words.every(w => t.includes(w)); });
}

/** Articles this admin can use: role level, custom-role permission (visible(href)) and plan (allows(href)). */
function visibleFor({ level, visible = () => true, allows = () => true }) {
  return ARTICLES.filter(a => level >= (LEVEL[a.minRole] || 1) && visible(a.href) && allows(a.href));
}

