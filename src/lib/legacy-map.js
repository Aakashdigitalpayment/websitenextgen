/** UTF-8 text that was stored as Latin-1 / Windows-1252 ("à¤¨à¥‡à¤ªà¤¾à¤²" → "नेपाल"); unchanged when it is not mojibake. */
function fixMojibake(s) {
  let cur = s;
  for (let round = 0; round < 3 && MOJIBAKE.test(cur); round++) {
    const bytes = [];
    for (const ch of cur) {
      const c = ch.codePointAt(0);
      if (c <= 0xff) bytes.push(c);
      else if (CP1252[c] !== undefined) bytes.push(CP1252[c]);
      else return cur;
    }
    let next;
    try { next = utf8.decode(Uint8Array.from(bytes)); } catch { return cur; }
    if (next === cur) break;
    cur = next;
  }
  return cur;
}

const blank = v => v === null || v === undefined || (typeof v === 'string' && v.trim() === '');
const DATE_RE = /^(\d{4})[-/.](\d{1,2})[-/.](\d{1,2})(?:[ T](\d{1,2}):(\d{2})(?::(\d{2}))?(?:\.\d+)?)?$/;
const pad = n => String(n).padStart(2, '0');
const validAd = (y, m, d) => { const t = new Date(Date.UTC(y, m - 1, d)); return t.getUTCFullYear() === y && t.getUTCMonth() === m - 1 && t.getUTCDate() === d; };

/**
 * A date / timestamp value → { value, kind } where kind names the repair (null when the value was fine).
 * BS dates (year ≥ 2070, often typed by admins into AD columns, sometimes in Devanagari digits) become AD.
 * futureIsBs: a birth date cannot be in the future — such a value is a BS date (e.g. 2050-01-15 BS = 1993 AD).
 */
function cleanDate(v, withTime, futureIsBs = false) {
  if (v instanceof Date) return Number.isNaN(v.getTime()) ? { value: null, kind: 'invalid_date' } : { value: v, kind: null };
  const raw = String(v).trim();
  if (/^0{4}-0{2}-0{2}/.test(raw)) return { value: null, kind: 'zero_date' };
  const s = nd.toLatinDigits(raw);
  const m = s.match(DATE_RE);
  if (!m) return { value: null, kind: 'invalid_date' };
  let [y, mo, d] = [Number(m[1]), Number(m[2]), Number(m[3])];
  let kind = s !== raw ? 'digits' : null;
  if (mo === 0 || d === 0) return { value: null, kind: 'zero_date' };
  if ((y >= 2070 && y <= 2100) || (futureIsBs && y > new Date().getFullYear() && y <= 2100)) {
    const ad = nd.bsToAd(`${y}-${pad(mo)}-${pad(d)}`);
    if (!ad) return { value: null, kind: 'invalid_date' };
    [y, mo, d] = ad.split('-').map(Number);
    kind = 'bs_date';
  }
  if (y < 1000 || !validAd(y, mo, d)) return { value: null, kind: 'invalid_date' };
  const date = `${y}-${pad(mo)}-${pad(d)}`;
  if (!withTime) return { value: date, kind };
  const time = m[4] !== undefined ? `${pad(m[4])}:${m[5]}:${m[6] || '00'}` : '00:00:00';
  if (Number(m[4] || 0) > 23 || Number(m[5] || 0) > 59 || Number(m[6] || 0) > 59) return { value: null, kind: 'invalid_date' };
  return { value: `${date} ${time}`, kind };
}

/** Birth-date columns: a future year means the value was typed in BS. */
const BIRTH_DATE = /^(dob|dob_ad|date_of_birth|birth_date|birthdate)$/;

const INT_RANGE = { smallint: 32767, integer: 2147483647, bigint: Number.MAX_SAFE_INTEGER };

/**
 * One value → the platform column's type. Returns { value, kind, archive } (kind null = unchanged / fine).
 * col: { type, max, nullable, hasDefault }
 */
function cleanValue(v, col) {
  if (v === undefined) return { value: undefined, kind: null };
  if (v === null) return { value: null, kind: null };
  const type = col.type;
  if (Buffer.isBuffer(v)) {
    if (type === 'bytea') return { value: v, kind: null };
    v = v.toString('utf8');
  }
  if (typeof v === 'boolean') v = v ? 1 : 0;
  if (typeof v === 'string') {
    let s = v.includes('\u0000') ? v.replace(/\u0000/g, '') : v;
    const fixed = fixMojibake(s);
    const moj = fixed !== s;
    s = fixed;
    const r = cleanTyped(s, col);
    if (moj && !r.kind) r.kind = 'mojibake';
    return r;
  }
  if (typeof v === 'number') {
    if (type in INT_RANGE) {
      if (!Number.isInteger(v)) return { value: Math.round(v), kind: 'rounded', archive: true };
      if (Math.abs(v) > INT_RANGE[type]) return { value: null, kind: 'out_of_range', archive: true };
      return { value: v, kind: null };
    }
    if (type === 'character varying' || type === 'text') return { value: String(v), kind: null };
    if (type === 'date' || type.startsWith('timestamp')) return cleanTyped(String(v), col);
    return { value: v, kind: null };
  }
  if (typeof v === 'object' && type === 'jsonb') return { value: JSON.stringify(v), kind: null };
  return { value: v, kind: null };
}

function cleanTyped(s, col) {
  const type = col.type;
  if (type in INT_RANGE) {
    const t = s.trim();
    if (t === '') return { value: null, kind: 'empty_number' };
    if (/^[+-]?\d+$/.test(t)) {
      const n = Number(t);
      return Math.abs(n) > INT_RANGE[type] ? { value: null, kind: 'out_of_range', archive: true } : { value: n, kind: null };
    }
    if (/^(true|yes|on)$/i.test(t)) return { value: 1, kind: 'boolean_text' };
    if (/^(false|no|off)$/i.test(t)) return { value: 0, kind: 'boolean_text' };
    const lat = nd.toLatinDigits(t).replace(/[,\s]/g, '');
    if (/^[+-]?\d+(\.0+)?$/.test(lat)) return { value: Math.trunc(Number(lat)), kind: 'number_text' };
    return { value: null, kind: 'invalid_number', archive: true };
  }
  if (type === 'numeric' || type === 'double precision' || type === 'real') {
    const t = s.trim();
    if (t === '') return { value: null, kind: 'empty_number' };
    if (/^[+-]?(\d+\.?\d*|\.\d+)(e[+-]?\d+)?$/i.test(t)) return { value: t, kind: null };
    const lat = nd.toLatinDigits(t).replace(/[,\s]|^(rs\.?|npr|रु\.?)/gi, '');
    if (/^[+-]?(\d+\.?\d*|\.\d+)$/.test(lat)) return { value: lat, kind: 'number_text' };
    return { value: null, kind: 'invalid_number', archive: true };
  }
  if (type === 'date' || type.startsWith('timestamp')) {
    if (s.trim() === '') return { value: null, kind: 'empty_date' };
    const r = cleanDate(s, type !== 'date', !!col.birth);
    return { value: r.value, kind: r.kind, archive: r.kind === 'invalid_date' };
  }
  if (type.startsWith('time')) {
    const t = s.trim();
    if (t === '') return { value: null, kind: 'empty_date' };
    return /^\d{1,2}:\d{2}(:\d{2})?$/.test(t) ? { value: t, kind: null } : { value: null, kind: 'invalid_time', archive: true };
  }
  if (type === 'jsonb' || type === 'json') {
    if (s.trim() === '') return { value: null, kind: 'empty_json' };
    try { JSON.parse(s); return { value: s, kind: null }; } catch { return { value: JSON.stringify(s), kind: 'json_wrapped' }; }
  }
  if (type === 'boolean') return { value: /^(1|true|yes|on)$/i.test(s.trim()), kind: null };
  if (col.max && [...s].length > col.max) return { value: [...s].slice(0, col.max).join(''), kind: 'truncated', archive: true };
  return { value: s, kind: null };
}

/** A legacy status word → the platform's word (same vocabulary as forms.js STATUS_LABELS); unknown words stay. */
function normaliseStatus(v) {
  if (blank(v)) return '';
  const raw = String(v).trim();
  const low = raw.toLowerCase().replace(/[\s-]+/g, '_');
  const mapped = STATUS_SYNONYMS[low] || STATUS_SYNONYMS[low.replace(/_/g, '')] || low;
  return STATUS_WORDS.has(mapped) ? mapped : raw;
}
function normaliseRole(v) {
  const low = String(v ?? '').trim().toLowerCase().replace(/[-\s]+/g, '_');
  return ROLE_MAP[low] || ROLE_MAP[low.replace(/_/g, ' ')] || low;
}

/** Where a source table goes: { action: 'copy'|'skip'|'archive', target, reason } */
function tablePlan(source, targetTables) {
  if (SKIP_TABLES[source]) return { action: 'skip', target: null, reason: SKIP_TABLES[source] };
  const target = TABLE_RENAMES[source] || source;
  if (targetTables.has(target)) return { action: 'copy', target, reason: TABLE_RENAMES[source] ? `renamed to ${target}` : '' };
  const rule = ARCHIVE_TABLES.find(([re]) => re.test(source));
  return { action: 'archive', target: null, reason: rule ? rule[1] : 'no equivalent table in the platform — rows kept in legacy_archive' };
}

/**
 * Where each source column goes: { direct: [col], mapped: {src: rule}, derived: {src: reason}, unmapped: [col] }
 * @param {string} table source table
 * @param {string[]} srcCols
 * @param {Map<string, object>} target platform columns (name → meta)
 */
function columnPlan(table, srcCols, target) {
  const rules = COLUMN_MAP[table] || {};
  const out = { direct: [], mapped: {}, derived: {}, unmapped: [] };
  for (const c of srcCols) {
    const r = rules[c];
    if (r && r.derived) out.derived[c] = r.derived;
    else if (r && r.to && target.has(r.to) && !target.has(c)) {
      if (r.when === 'missing' && srcCols.includes(r.to)) out.unmapped.push(c);
      else out.mapped[c] = r;
    } else if (target.has(c)) out.direct.push(c);
    else out.unmapped.push(c);
  }
  return out;
}

/** Key of a source row (id, the table's key columns, or the row number). */
function rowKey(table, row, index) {
  if (row.id !== undefined && row.id !== null && row.id !== '') return String(row.id);
  const k = KEY_COLUMNS[table];
  if (k && k.every(c => !blank(row[c]))) return k.map(c => String(row[c])).join('|');
  return '#' + (index + 1);
}

/**
 * Transform one source row for the platform.
 * @param {string} table      platform table
 * @param {object} row        source row (column → value; undefined = not in the dump's INSERT)
 * @param {object} plan       columnPlan()
 * @param {Map} target        platform column meta (name → { type, max, nullable, hasDefault })
 * @param {object} ctx        { piiKey, schema }
 * @returns {{ values: object, repairs: {col, kind}[], archive: object|null }}
 */
function transformRow(table, row, plan, target, ctx = {}) {
  const values = {};
  const repairs = [];
  const archive = {};
  const rep = (col, kind, original, keep) => { repairs.push({ col, kind }); if (keep && original !== undefined && original !== null && original !== '') archive[col] = toJsonValue(original); };

  for (const c of plan.direct) {
    const meta = BIRTH_DATE.test(c) ? { ...target.get(c), birth: true } : target.get(c);
    const r = cleanValue(row[c], meta);
    if (r.kind) rep(c, r.kind, row[c], r.archive);
    values[c] = r.value;
  }
  // older column names: fill the platform column when it is empty (else keep the old value in the archive)
  for (const [src, rule] of Object.entries(plan.mapped)) {
    const meta = target.get(rule.to);
    let v = row[src];
    if (blank(v)) continue;
    if (rule.value) { v = rule.value(v); if (v === undefined) { rep(src, 'unmapped_value', row[src], true); continue; } }
    const r = cleanValue(v, meta);
    const cur = values[rule.to];
    const empty = blank(cur) || (rule.zeroIsEmpty && Number(cur) === 0);
    if (empty) { values[rule.to] = r.value; repairs.push({ col: rule.to, kind: 'mapped_from_' + src }); }
    else if (String(cur) !== String(r.value)) archive[src] = toJsonValue(row[src]);
  }
  for (const src of Object.keys(plan.derived)) if (!blank(row[src])) archive[src] = toJsonValue(row[src]);
  for (const src of plan.unmapped) if (!blank(row[src])) archive[src] = toJsonValue(row[src]);

  // statuses and roles in the platform's vocabulary
  for (const c of Object.keys(values)) {
    if (STATUS_COLUMNS.has(c) && typeof values[c] === 'string') {
      const s = normaliseStatus(values[c]);
      if (s === '') { values[c] = undefined; rep(c, 'status_default', row[c], false); }
      else if (s !== values[c]) { rep(c, 'status', row[c], s !== values[c].trim().toLowerCase()); values[c] = s; }
    }
  }
  if (table === 'admin_users' && typeof values.role === 'string') {
    const r = normaliseRole(values.role);
    if (r !== values.role) { rep('role', 'role', row.role, false); values.role = r; }
  }
  if (ROW_RULES[table]) { const k = ROW_RULES[table](values, row); if (k) repairs.push({ col: 'status', kind: k }); }
  if (table === 'members' && typeof values.sadasyata_number === 'string' && values.sadasyata_number !== values.sadasyata_number.trim()) {
    values.sadasyata_number = values.sadasyata_number.trim();
    rep('sadasyata_number', 'trimmed', null, false);
  }
  // PHP-encrypted PII (pii1:/pii2:) → the platform's per-tenant encryption, when the old key is known
  for (const c of pii.PII_COLUMNS[table] || []) {
    const v = values[c];
    if (typeof v === 'string' && /^pii[12]:/.test(v) && ctx.piiKey) {
      const plain = pii.decryptLegacy(v, ctx.piiKey);
      if (plain !== v) { values[c] = pii.encrypt(plain, ctx.schema); repairs.push({ col: c, kind: 'pii_converted' }); }
    }
  }
  // NOT NULL columns: an explicit NULL takes the column default (or the type's empty value)
  for (const [c, v] of Object.entries(values)) {
    if (v !== null) continue;
    const meta = target.get(c);
    if (meta.nullable) continue;
    if (meta.hasDefault) { values[c] = undefined; repairs.push({ col: c, kind: 'null_default' }); }
    else { values[c] = emptyOf(meta); repairs.push({ col: c, kind: 'null_filled' }); }
  }
  return { values, repairs, archive: Object.keys(archive).length ? archive : null };
}

/** Empty value of a platform type (for NOT NULL columns without a default). */
function emptyOf(meta) {
  if (meta.type in INT_RANGE || meta.type === 'numeric') return 0;
  if (meta.type === 'date') return '1970-01-01';
  if (meta.type.startsWith('timestamp')) return '1970-01-01 00:00:00';
  if (meta.type === 'jsonb') return '{}';
  if (meta.type === 'boolean') return false;
  return '';
}

/** A source value as JSON-safe data (Buffers as base64). */
function toJsonValue(v) {
  if (Buffer.isBuffer(v)) { const s = v.toString('utf8'); return Buffer.from(s, 'utf8').equals(v) ? s : { base64: v.toString('base64') }; }
  if (v instanceof Date) return Number.isNaN(v.getTime()) ? String(v) : v.toISOString();
  if (typeof v === 'bigint') return v.toString();
  return v;
}
const rowToJson = row => Object.fromEntries(Object.entries(row).filter(([, v]) => v !== undefined).map(([k, v]) => [k, toJsonValue(v)]));

/** Legacy fixValue (older callers / tests): one value cleaned for a type name. */
function fixValue(v, pgType) {
  const r = cleanValue(v === undefined ? null : v, { type: pgType || 'text', nullable: true });
  return r.value === undefined ? null : r.value;
}

